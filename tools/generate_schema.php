<?php
// F207: regenerate includes/schema.php (the fresh-install schema) from a database.
// Usage: php tools/generate_schema.php /path/to/repaired/site.db > includes/schema.php
// Use a copy of the production database AFTER db/repair/repair.sql has been applied. Only the
// structure is read (CREATE TABLE / CREATE INDEX statements); no rows are copied.
if ($argc < 2 || !is_file($argv[1])) {
    fwrite(STDERR, "usage: php tools/generate_schema.php <site.db>\n");
    exit(1);
}
$db = new PDO('sqlite:' . $argv[1], null, null, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$rows = $db->query("SELECT type, name, sql FROM sqlite_master
                    WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' AND type IN ('table', 'index')
                    ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, name")->fetchAll(PDO::FETCH_ASSOC);
$stmts = [];
foreach ($rows as $r) {
    $sql = preg_replace('/^\s*CREATE\s+(UNIQUE\s+)?(TABLE|INDEX)\s+(?!IF\s+NOT\s+EXISTS)/i', 'CREATE $1$2 IF NOT EXISTS ', $r['sql']);
    $stmts[] = $sql;
}
echo "<?php\n";
echo "// F207: complete schema for a fresh install, generated by tools/generate_schema.php from the\n";
echo "// repaired production database (structure only, no data). includes/db.php runs it only when\n";
echo "// the database has no users table. Do not edit by hand; regenerate instead.\n";
echo "// Tables: " . count(array_filter($rows, fn($r) => $r['type'] === 'table')) . ", indexes: " . count(array_filter($rows, fn($r) => $r['type'] === 'index')) . "\n";
echo "return " . var_export($stmts, true) . ";\n";
